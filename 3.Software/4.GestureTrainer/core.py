"""Dataset validation and safe firmware export; no machine learning dependency needed."""
from __future__ import annotations
import csv
import hashlib
import json
import math
from pathlib import Path
import re
import shutil
from datetime import datetime

ACTIONS = ['外部关灯', '外部开灯', '键盘向上', '键盘向下', '隔空鼠标', '照明魔法', '音量旋钮', '空中光绘']
WINDOW = 100
FEATURES = 2
CLASSES = len(ACTIONS)

def stamp():
    return datetime.now().strftime('%Y%m%d-%H%M%S-%f')

def read_samples(directory: Path, minimum: int = 10, names=None):
    """Return unique samples; reject conflicting labels, NaN and broken rows."""
    names = ACTIONS if names is None else names
    samples, labels, counts, seen = [], [], [], {}
    for label in range(len(names)):
        path = directory / f'{label}.csv'
        if not path.is_file():
            raise ValueError(f'“{names[label]}”还没有样本，请先采集。')
        count = 0
        with path.open(encoding='utf-8-sig', newline='') as file:
            for line, row in enumerate(csv.reader(file), 1):
                if not row:
                    continue
                if len(row) != 201:
                    raise ValueError(f'{path.name} 第 {line} 行应为 201 列，实际为 {len(row)} 列。')
                try:
                    row_label = int(row[0])
                    values = [float(value) for value in row[1:]]
                except ValueError as exc:
                    raise ValueError(f'{path.name} 第 {line} 行含无效数字。') from exc
                if row_label != label or not all(math.isfinite(value) for value in values):
                    raise ValueError(f'{path.name} 第 {line} 行的类别不匹配，或数据含无效值。')
                key = tuple(values)
                if key in seen:
                    if seen[key] != label:
                        raise ValueError('同一个动作样本被标记成不同功能，请检查数据。')
                    continue
                seen[key] = label
                samples.append(values)
                labels.append(label)
                count += 1
        counts.append(count)
        if count < minimum:
            raise ValueError(f'“{names[label]}”只有 {count} 条不重复有效记录，至少需要 {minimum} 条。')
    return samples, labels, counts

def dataset_counts(directory: Path):
    counts = []
    for label in range(CLASSES):
        path = directory / f'{label}.csv'
        if not path.is_file():
            counts.append(0)
            continue
        with path.open(encoding='utf-8-sig', newline='') as file:
            counts.append(sum(bool(row) for row in csv.reader(file)))
    return counts

def backup(path: Path, directory: Path):
    if path.exists():
        directory.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, directory / f'{path.stem}-{stamp()}{path.suffix}')

def model_header(blob: bytes):
    rows = [', '.join(f'0x{value:02x}' for value in blob[i:i + 12]) for i in range(0, len(blob), 12)]
    return ('#pragma once\n\n// Generated by MugglesWand Gesture Trainer.\n'
            'alignas(16) const unsigned char gesture_model_tflite[] = {\n    '
            + ',\n    '.join(rows) + '\n};\n'
            + f'const unsigned int gesture_model_tflite_len = {len(blob)};\n')

def patched_inference(source: str, mean, std, classes=CLASSES):
    """Preserve the existing gold UI and code; only replace model constants."""
    for name, values in [('kMean', mean), ('kStd', std)]:
        replacement = f'constexpr float {name}[2] = ' + '{' + ', '.join(f'{float(v):.9e}f' for v in values) + '};'
        source, changed = re.subn(rf'constexpr\s+float\s+{name}\s*\[\s*2\s*\]\s*=\s*\{{[^}}]*\}}\s*;', replacement, source)
        if changed != 1:
            raise ValueError(f'固件中的 {name} 格式无法识别，没有修改任何源文件。')
    source, changed = re.subn(r'constexpr\s+int\s+kNumClasses\s*=\s*\d+\s*;', f'constexpr int kNumClasses = {classes};', source)
    if changed != 1:
        raise ValueError('无法识别固件的类别数量，请使用本工具配套的固件模板。')
    # Match the desktop INT8 evaluation: round and clamp instead of overflowing int8_t.
    quantizer = re.compile(r'int8_t quantized = static_cast<int8_t>\(\s*normalized / input->params.scale \+ input->params.zero_point\);')
    source, changed = quantizer.subn(
        'int32_t value = static_cast<int32_t>(roundf(normalized / input->params.scale + input->params.zero_point));\n'
        '                int8_t quantized = static_cast<int8_t>(value < -128 ? -128 : (value > 127 ? 127 : value));', source)
    if changed != 1:
        raise ValueError('无法识别固件的输入量化逻辑，请使用配套固件模板。')
    source = '#include <math.h>\n' + source
    return source

def export_model(directory: Path, blob: bytes, mean, std, template: Path, report: dict):
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'gesture_model.tflite').write_bytes(blob)
    patch = directory / 'firmware_patch'
    patch.mkdir()
    (patch / 'gesture_model.h').write_text(model_header(blob), encoding='utf-8')
    source = (template / 'src/Model/gesture_inference.cpp').read_text(encoding='utf-8')
    (patch / 'gesture_inference.cpp').write_text(patched_inference(source, mean, std, len(report.get("counts", ACTIONS))), encoding='utf-8')
    report.update(mean=list(map(float, mean)), std=list(map(float, std)),
                  model_sha256=hashlib.sha256(blob).hexdigest(), model_bytes=len(blob))
    if not report.get('gestures'):
        report['actions'] = ACTIONS
    (directory / 'report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    instructions = (
        '这是训练模型包，不是可以直接上传的固件。\n'
        '在工具中点击“生成升级固件”，会复制配套固件工程、自动更新模型与参数并编译。\n'
        '也可把 firmware_patch 下两个文件放进配套固件 src/Model/ 目录，再用 PlatformIO 编译。\n'
        '编译生成的 firmware.bin 才能用于应用升级，gesture_model.tflite 不能直接上传。\n'
        '手势标签以模型报告为准；功能对应在升级后的魔杖网页配置，保存后立即生效。\n'
        '测试准确率来自留出的样本，不代表实物使用准确率；请用新动作实际验证。\n')
    if report.get('gestures'):
        instructions = ('这是自定义手势的识别模型，功能对应由魔杖保存。\n'
                        '请在电脑训练工具生成升级固件并OTA安装，再打开魔杖网页的“手势与功能”。\n'
                        '功能保存后立即生效，不用重新训练、编译或OTA。首次安装新手势模型默认不执行功能。\n'
                        '不能直接复制两个模型文件；须由配套工具生成正确的手势标签与配置支持。\n'
                        '模型 .tflite 不能直接上传到OTA。请使用工具生成的应用固件。\n'
                        '请用新动作独立验证，不把训练内测试准确率视为实物精度。\n')
    (directory / '使用说明.txt').write_text(instructions, encoding='utf-8')
    return report
